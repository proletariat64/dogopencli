"""Rebuild sampled schemas from the sanitized, committed liquidity probe report.

Run: python scripts/build_liquidity_fields.py [--check]
Includes every populated scope (including previous-day samples), only for
registered method/path pairs. Observed types are not validation guarantees.
"""

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path
from pprint import pformat

ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    ROOT / "docs/research/general/2026-10-01-liquidity-live-probes.md",
    ROOT / "docs/research/general/2026-10-02-liquidity-spec76-field-evidence.md",
)
TARGET = ROOT / "src/dogopencli/plugins/liquidity/fields.py"


def build() -> str:
    sys.path.insert(0, str(ROOT / "src"))
    from dogopencli.plugins.liquidity.leaves import DETAIL_LEAVES, LIST_LEAVES

    contracts: dict[str, set[tuple[str, str]]] = defaultdict(set)
    for leaf in LIST_LEAVES.values():
        for variant in leaf.variants:
            contracts[variant.name].add((variant.method, variant.endpoint))
    for detail in DETAIL_LEAVES.values():
        contracts[detail.spec.name].add((detail.spec.method, detail.spec.endpoint))
    observed: dict[str, dict[str, dict[str, set[str]]]] = {}
    for evidence in SOURCES:
        for section in re.split(r"^### ", evidence.read_text(), flags=re.MULTILINE)[1:]:
            heading = section.splitlines()[0].split(" / ", 1)[0]
            name = "liquidity." + heading.replace(" ", ".")
            source = re.search(r"Source: `(GET|POST) ([^`]+)`", section)
            sample = re.search(r"^Sample fields: (.+)$", section, re.MULTILINE)
            if (
                not source
                or not sample
                or source.groups() not in contracts.get(name, set())
            ):
                continue
            fields = observed.setdefault(name, {}).setdefault(source[2], {})
            if evidence == SOURCES[-1]:
                # Projected v0.2.3 schemas replace older mixed-field samples.
                fields.clear()
            for field, types in re.findall(r"`([^`]+)` \(([^)]+)\)", sample[1]):
                fields.setdefault(field, set()).update(types.split("|"))
    merged: dict[str, dict[str, str]] = {}
    variants: dict[str, dict[str, dict[str, str]]] = {}
    for name, endpoints in sorted(observed.items()):
        union: dict[str, set[str]] = defaultdict(set)
        for fields in endpoints.values():
            for field, types in fields.items():
                union[field].update(types)
        merged[name] = {
            field: "|".join(sorted(types)) for field, types in sorted(union.items())
        }
        if len(contracts[name]) > 1:
            variants[name] = {
                endpoint: {
                    field: "|".join(sorted(types))
                    for field, types in sorted(fields.items())
                }
                for endpoint, fields in sorted(endpoints.items())
            }
    missing = contracts.keys() - merged.keys()
    if missing:
        raise ValueError(
            f"registered capabilities without sampled evidence: {sorted(missing)}"
        )
    header = '''"""Sampled field/type evidence (observed 2026-10-01 and 2026-10-02).

Generated by scripts/build_liquidity_fields.py from committed sanitized
probe reports, including populated previous-day and projected v0.2.3 scopes.
Samples are not
complete schemas, validation assertions, or nullability guarantees.
"""

'''
    return (
        header
        + "SAMPLED_FIELDS: dict[str, dict[str, str]] = "
        + pformat(merged, width=88, sort_dicts=True)
        + "\n\nVARIANT_SAMPLED_FIELDS: dict[str, dict[str, dict[str, str]]] = "
        + pformat(variants, width=88, sort_dicts=True)
        + "\n"
    )


def main() -> int:
    import subprocess

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = subprocess.run(
        ["ruff", "format", "--stdin-filename", str(TARGET), "-"],
        input=build(),
        text=True,
        capture_output=True,
        check=True,
    ).stdout
    if args.check:
        if TARGET.read_text() != result:
            parser.error("fields.py is stale; run scripts/build_liquidity_fields.py")
    else:
        TARGET.write_text(result)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
